def fit_logistic(Xtr, ytr, wtr, Xte):
    """L2 logistic regression on all standardized features.

    The linear ceiling. If a sign signal is linearly present at all, this
    finds it; C is chosen by the fold's own calibration slice, never by the
    test slice.
    """
    from sklearn.linear_model import LogisticRegression
    from sklearn.preprocessing import StandardScaler

    sc = StandardScaler().fit(Xtr)
    m = LogisticRegression(C=0.01, max_iter=2000, solver="lbfgs")
    m.fit(sc.transform(Xtr), ytr, sample_weight=wtr)
    return m.predict_proba(sc.transform(Xte))[:, 1]


def fit_gbdt(Xtr, ytr, wtr, Xte, seed=0):
    """Gradient boosting -- the nonlinear ceiling.

    Deliberately shallow and heavily regularized. An unconstrained GBDT on
    500k overlapping episodes will fit the sample perfectly and tell us
    nothing about the population; the question here is whether ANY nonlinear
    structure survives out of sample, not how well one can memorize.
    """
    from sklearn.ensemble import HistGradientBoostingClassifier

    m = HistGradientBoostingClassifier(
        max_depth=3, max_iter=200, learning_rate=0.05,
        l2_regularization=1.0, min_samples_leaf=200,
        early_stopping=False, random_state=seed,
    )
    m.fit(Xtr, ytr, sample_weight=wtr)
    return m.predict_proba(Xte)[:, 1]


def fit_noctua_pup(ep, X, m_tr, m_te, hidden=32, seeds=3):
    """NOCTUA's OWN direction call, `infer.prob_up`, trained per fold.

    This is the shipped configuration -- `serve_consistent`, i.e. stage B
    retargeted onto the causal `exp(har_1d)*sqrt(H)` reference -- so the number
    is what the deployed model would have said, not what some other variant
    would have.

    prob_up integrates the terminal-return head `q_r` against zero, mixed over
    the 32 volatility atoms.

    Worth being precise about what this head is, because the convenient story
    is wrong. `q_r` is NOT an unsupervised by-product: `train.py:179` puts
    `pinball_loss(qr, r)` -- a strictly proper scoring rule on the signed
    standardized return R/sigma -- directly into the objective, alongside the
    two excursion heads. The model is explicitly trained to get the location
    of the return distribution right, and the sign call falls out of that.

    So if it has no directional skill, the explanation cannot be "nobody
    asked it to". It is either that the signal is absent, or that a location
    shift small enough to move P(R>0) from 0.500 to 0.520 is below what a
    17-point quantile grid fitted on this much noise can resolve. The
    attainability arms in this file exist to tell those two apart.
    """
    H = ep["H"].to_numpy(np.float64)
    raw = np.exp(X["har_1d"].to_numpy(np.float64)) * np.sqrt(H)
    lo, hi = np.quantile(raw[m_tr], [0.005, 0.995])
    sigma_ref = np.maximum(np.clip(raw, lo, hi), 1e-12)

    tr, stds = prepare(ep, X, m_tr, sigma_ref=sigma_ref[m_tr])
    wtr = S.sample_weights(ep, m_tr)
    yall = B.har_target(ep.RV.to_numpy(), H)
    ols = B.OLS(BASE_COLS).fit(pd.DataFrame(tr["Xb"], columns=BASE_COLS),
                               tr["y"].astype(np.float64), wtr)
    bl = B.fit_vol_baselines(X[m_tr], yall[m_tr], wtr)
    models = [train_model(tr, wtr, tr, hidden=hidden, epochs=40, seed=s,
                          ols_beta=ols.beta)[0] for s in range(seeds)]

    d, _ = prepare(ep, X, m_te, *stds)
    lp = bl["log_har_cal"].predict(X[m_te])
    preds = [I.predict(m, d, har_logvol=lp) for m in models]
    avg = dict(preds[0])
    for k in ("qa", "sigma_atoms", "q_r", "q_up", "q_dn"):
        avg[k] = np.mean([p[k] for p in preds], axis=0)
    return I.prob_up(avg)


def fit_momentum(Xtr, ytr, wtr, Xte):
    """One feature: the trailing 1-day return, through a fitted logistic.

    A control for the most-published crypto anomaly. If short-horizon momentum
    or reversal exists here, this is the minimal estimator that would see it,
    and it cannot be accused of overfitting 42 dimensions.
    """
    from sklearn.linear_model import LogisticRegression
    from sklearn.preprocessing import StandardScaler

    cols = ["mom_ret_1d"]
    sc = StandardScaler().fit(Xtr[cols])
    m = LogisticRegression(C=1.0, max_iter=1000)
    m.fit(sc.transform(Xtr[cols]), ytr, sample_weight=wtr)
    return m.predict_proba(sc.transform(Xte[cols]))[:, 1]


