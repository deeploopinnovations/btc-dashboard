def shuffled_dsc_null(p, y, n_rep=200, seed=0):
    """Distribution of DSC when the forecast carries no conditional signal.

    Permuting p against y destroys the pairing while leaving both marginals
    and the in-sample isotonic fit exactly as they are, which is precisely the
    quantity that makes raw DSC uninterpretable.
    """
    rng = np.random.default_rng(seed)
    out = np.empty(n_rep)
    for i in range(n_rep):
        out[i] = corp_decomposition(rng.permutation(p), y)["DSC"]
    return out


def block_bootstrap_ci(d, n_rep=2000, seed=0, alpha=0.05):
    """Moving-block bootstrap CI for the mean of a dependent series.

    Block length n^(1/3) is the standard choice for a stationary bootstrap of
    a mean under weak dependence. `d` is a per-episode loss DIFFERENCE, so the
    interval answers: is one forecaster better than the other, allowing for
    the fact that neighbouring episodes share most of their window?
    """
    d = np.asarray(d, dtype=np.float64)
    n = len(d)
    if n < 20:
        return (float("nan"), float("nan"))
    L = max(1, int(round(n ** (1 / 3))) if block_len is None else int(block_len))
    L = min(L, n)
    nb = int(np.ceil(n / L))
    rng = np.random.default_rng(seed)
    starts = rng.integers(0, n - L + 1, size=(n_rep, nb))
    idx = (starts[:, :, None] + np.arange(L)[None, None, :]).reshape(n_rep, -1)[:, :n]
    means = d[idx].mean(axis=1)
    return (float(np.quantile(means, alpha / 2)), float(np.quantile(means, 1 - alpha / 2)))


def mean_ci(d, n_rep: int = 20_000, seed: int = 0, alpha: float = 0.05,
            block_len: int | None = None) -> dict:
    """A CI for the mean that is DEFINED at every usable n, plus the diagnostics
    that matter when n is small.

    `block_bootstrap_ci` returns (nan, nan) below n = 20. That guard is correct
    for its intended argument -- a per-episode loss difference with fewer than
    20 points means the caller made a mistake -- but it is a trap for any
    caller whose unit is a FOLD. `eval/anchor_freshness.py` fed it six yearly
    deltas, got (nan, nan), and its pre-registered condition

        spike QLIKE CI excludes zero favourably

    evaluated to False -- because `nan < 0` is False, not because the data said
    so. The verdict happened to be right; the mechanism that produced it was
    not looking at the data at all. A rule decided by a NaN is not a rule.

    Three numbers are returned rather than one, because at n = 6 the choice of
    estimator is a real degree of freedom and hiding it would be a way to pick
    the answer:

      ci95        the moving-block interval, blocks of round(n^(1/3)) unless
                  `block_len` overrides it. This is the PRE-REGISTERED
                  estimator and the one a verdict uses.

    `block_len` exists because n^(1/3) is a rule of thumb about SAMPLE SIZE and
    knows nothing about the dependence it is supposed to absorb. When the unit
    is an episode drawn from an hourly-anchored table with an H-hour forward
    window, consecutive observations share H-1 of their H hours, and the
    dependence range is H regardless of n. At H = 168 and n = 49,000 the rule of
    thumb gives 37 -- roughly a fifth of the overlap -- and the resulting
    interval is too narrow for the reason that matters: it is treating four
    fifths of a shared window as independent evidence. Callers that know their
    dependence range should say so.
      ci95_iid    the ordinary bootstrap. For yearly folds separated by an
                  embargo the dependence the blocks model is largely absent,
                  so the block interval is if anything conservative; when the
                  two disagree in sign of coverage, say so rather than picking.
      n_favourable / n  the sign count, which no bootstrap can launder.
    """
    d = np.asarray(d, dtype=np.float64)
    d = d[np.isfinite(d)]
    n = len(d)
    if n < 2:
        raise ValueError(f"mean_ci needs at least 2 finite observations, got {n}")
    L = max(1, int(round(n ** (1 / 3))) if block_len is None else int(block_len))
    L = min(L, n)
    nb = int(np.ceil(n / L))
    rng = np.random.default_rng(seed)

    # CHUNKED. The obvious vectorisation builds an (n_rep, n) index array, which
    # is 20,000 x 49,118 = 982M int64 = 7.9 GB and killed the direction
    # benchmark with SIGKILL. It was fine at n = 1,681 (0.3 GB) and became a
    # problem the moment STATS_PROTOCOL made the paired per-episode estimator
    # primary -- i.e. the fix that improved the statistics moved this onto the
    # hot path. Chunking bounds peak memory at CHUNK x n regardless of n_rep.
    chunk = max(1, min(n_rep, int(2e7 // max(n, 1)) or 1))
    blk = np.empty(n_rep, dtype=np.float64)
    iid = np.empty(n_rep, dtype=np.float64)
    off = np.arange(L)[None, None, :]
    done = 0
    while done < n_rep:
        m = min(chunk, n_rep - done)
        starts = rng.integers(0, n - L + 1, size=(m, nb))
        idx = (starts[:, :, None] + off).reshape(m, -1)[:, :n]
        blk[done:done + m] = d[idx].mean(axis=1)
        iid[done:done + m] = d[rng.integers(0, n, size=(m, n))].mean(axis=1)
        done += m
    q = lambda a: (float(np.quantile(a, alpha / 2)), float(np.quantile(a, 1 - alpha / 2)))
    # NOTE the key name: `ci95` carries whatever `alpha` was requested, so at
    # alpha = 0.025 it is a 97.5% interval despite the name. `level` is
    # returned alongside precisely so a caller reporting a Bonferroni-adjusted
    # interval cannot label it 95% by copying the key.
    return {"mean": float(d.mean()), "n": n, "block_len": L,
            "level": float(1.0 - alpha),
            "ci95": list(q(blk)), "ci95_iid": list(q(iid)),
            "n_negative": int((d < 0).sum()), "n_positive": int((d > 0).sum()),
            "sd": float(d.std(ddof=1)) if n > 1 else float("nan")}


def small_n_inference(d, alpha: float = 0.05) -> dict:
    """The honest tools at fold-level n, where the bootstrap is not one.

    A statistical audit established that a resampling interval over n same-signed
    fold deltas excludes zero at every alpha by construction (pitfalls check 13).
    At this n the defensible instruments are:

      t-interval          proper for a small sample with estimated variance, and
                          it WIDENS with alpha, which the bootstrap stopped doing
                          past alpha/3.
      exact sign-flip     the permutation test the paired fold design actually
      permutation         licenses: enumerate all 2^n sign assignments. Its
                          one-sided p has a HARD FLOOR of 2^-n -- 0.03125 at
                          n = 5 -- so at that n it can never clear a Bonferroni
                          threshold with family >= 2, however large the effect.
                          That floor is a property of the DESIGN and is returned
                          explicitly so it can be checked before running.

    Reported together because they disagree usefully: the t-interval can clear
    while the permutation floor forbids corrected significance, and a reader is
    entitled to see both rather than whichever one the author preferred.
    """
    from itertools import product

    d = np.asarray(d, dtype=np.float64)
    d = d[np.isfinite(d)]
    n = len(d)
    if n < 2:
        raise ValueError(f"small_n_inference needs at least 2 observations, got {n}")
    mean = float(d.mean())
    se = float(d.std(ddof=1) / np.sqrt(n))
    out = {"n": n, "mean": mean, "se": se, "sd": float(d.std(ddof=1)),
           "all_same_sign": bool((d > 0).all() or (d < 0).all())}
    try:
        from scipy import stats
        crit = float(stats.t.ppf(1 - alpha / 2, n - 1))
        out["t_ci"] = [mean - crit * se, mean + crit * se]
        out["t_p_two_sided"] = float(stats.ttest_1samp(d, 0.0).pvalue)
        # MDE at 80% power with the correct noncentral-t critical values, not
        # the z approximation (z_.975 + z_.80 = 2.80), which understates by
        # ~25-35% at n = 5-6.
        out["mde_80"] = float((crit + stats.t.ppf(0.80, n - 1)) * se)
    except Exception:
        out["t_ci"] = None
    if n <= 22:                      # 2^22 is the practical enumeration limit
        signs = np.array(list(product([1.0, -1.0], repeat=n)))
        perm = (signs * d).mean(axis=1)
        p_one = float((perm <= mean).mean() if mean < 0 else (perm >= mean).mean())
        out["perm_p_one_sided"] = p_one
        out["perm_p_floor"] = float(2.0 ** (-n))
        out["perm_at_floor"] = bool(abs(p_one - 2.0 ** (-n)) < 1e-12)
    return out


def ci_excludes_zero(ci, favourable_sign: int) -> bool:
    """Did the interval clear zero on the stated side? REFUSES a NaN interval.

    `favourable_sign` is -1 when a NEGATIVE delta is the win (a loss went down)
    and +1 when a positive delta is. Passing an undefined interval raises
    instead of silently answering False -- see `mean_ci`.
    """
    lo, hi = float(ci[0]), float(ci[1])
    if not (np.isfinite(lo) and np.isfinite(hi)):
        raise ValueError(
            f"refusing to decide a pre-registered condition against an "
            f"undefined interval [{lo}, {hi}]; a NaN comparison answers False "
            f"without consulting the data")
    return hi < 0 if favourable_sign < 0 else lo > 0


def score_all(name, p, y, seed=0, null_reps=200):
    p = np.clip(np.asarray(p, dtype=np.float64), EPS, 1 - EPS)
    y = np.asarray(y, dtype=np.float64)
    c = corp_decomposition(p, y)
    null = shuffled_dsc_null(p, y, n_rep=null_reps, seed=seed)
    return {
        "model": name,
        "n": int(len(y)),
        "log_loss": log_score(p, y),
        "brier": c["brier"],
        "MCB": c["MCB"],
        "DSC": c["DSC"],
        "UNC": c["UNC"],
        "DSC_null_p95": float(np.quantile(null, 0.95)),
        "DSC_null_mean": float(null.mean()),
        "clears_null": bool(c["DSC"] > np.quantile(null, 0.95)),
        "mean_p": float(p.mean()),
        "base_rate": c["base_rate"],
    }


