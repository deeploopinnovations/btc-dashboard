"""
eval/direction.py
=====================================================================
Does ANYTHING in this feature set predict the SIGN of the BTC return?

WHY THIS FILE EXISTS

The project has two stated goals: forecast volatility, and forecast direction.
Volatility has been measured to death -- six folds, five baselines, adversarial
controls, per-expiry decomposition. Direction has been measured ONCE, as a
two-row table in `noctua/evaluate.py`, on a single split, with the v1 model:

    NOCTUA        log_loss 0.694344   brier 0.250581
    constant_50   log_loss 0.693147   brier 0.250000

NOCTUA lost to a coin flip and nobody followed up. That asymmetry of attention
is itself the finding: the half of the mandate that was easy to move got all
the measurement, and the half that matters commercially got a footnote.

WHAT WOULD BE WRONG WITH JUST RE-RUNNING THAT TABLE

It cannot distinguish the two explanations, and they call for opposite work:

  (a) MODEL FAILURE. The signal is in the features and this model throws it
      away -- through the coarseness of a 17-point quantile grid, the
      coupling penalty that ties the return head to the two excursion heads,
      or the sheer dominance of the volatility terms in a shared trunk. If
      so: a dedicated directional head is worth building.

  (b) EFFICIENT-MARKET NULL. There is no exploitable sign information at a
      6-24 hour horizon in trailing price/vol features, for anyone, with any
      architecture. If so: no head will help, and the honest deliverable is a
      measured ceiling plus a decision to stop paying for it.

Telling them apart needs an ATTAINABILITY test, not another model score. So
this file fits the strongest sign predictors the feature set admits -- L2
logistic, gradient boosting, and a momentum-only control -- walk-forward, and
asks whether ANY of them clears the discrimination null. That is a ceiling on
what the 42 features contain about sign, and NOCTUA is scored against it.

THE STATISTICS, AND WHY THE OBVIOUS VERSION LIES

DSC from `corp_decomposition` is computed with an IN-SAMPLE isotonic fit, so it
is mechanically positive even for pure noise: PAV finds a monotone staircase in
any finite sample. Comparing DSC to zero is therefore meaningless. The null is
generated by SHUFFLING the predictions against the outcomes -- marginals and
the isotonic machinery intact, conditional information destroyed -- and the
observed DSC has to clear that distribution's upper tail. This is the same
control that retracted the "Kronos carries conditional information" claim in
BENCHMARK.md section 5, where a forecaster cleared zero comfortably and the
shuffled p95 not at all.

Episodes at consecutive anchors overlap by design (a 19-hour window opened
every hour shares 18 hours with its neighbour), so IID resampling would give
intervals several times too narrow. Confidence intervals use a MOVING-BLOCK
bootstrap with block length n^(1/3), which keeps the local dependence intact.

TWO TEST SLICES, DELIBERATELY

  production  H = 19, anchor 17:00 UTC -- what actually ships. ~365 episodes
              per fold, which is honest but nearly powerless for a sign test:
              distinguishing a true 52% edge from 50% needs thousands.
  wide        every H = 19 anchor hour -- ~8,700 per fold. Overlapping, hence
              the block bootstrap, but it is where the power is.

Reporting only the first would be under-powered; reporting only the second
would flatter the deployed configuration. Both are reported.

    python -m model.eval.direction --out model/artifacts/direction.json
"""
